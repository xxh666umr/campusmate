/**
 * 「信息选择」咨询方式的数据源：
 * 用户先选类别，再选具体问题，机器人给出推荐处理办法。
 */
class GuidedFlow
{
    public static function tree(): array
    {
        $out = [];
        foreach (self::data() as $cat) {
            $out[] = [
                'id'     => $cat['id'],
                'name'   => $cat['name'],
                'icon'   => $cat['icon'],
                'desc'   => $cat['desc'],
                'count'  => count($cat['issues']),
                'issues' => $cat['issues'],
            ];
        }
        return $out;
    }

    public static function category(string $id): ?array
    {
        foreach (self::data() as $cat) {
            if ($cat['id'] === $id) {
                return $cat;
            }
        }
        return null;
    }

    public static function issue(string $catId, string $issueId): ?array
    {
        $cat = self::category($catId);
        if (!$cat) {
            return null;
        }
        foreach ($cat['issues'] as $issue) {
            if ($issue['id'] === $issueId) {
                $issue['category'] = $cat['name'];
                $issue['category_id'] = $cat['id'];
                return $issue;
            }
        }
        return null;
    }

    /** 根据自由文本粗匹配一个问题（用于多轮对话里引导） */
    public static function match(string $text): ?array
    {
        $best = null;
        $bestScore = 0;
        foreach (self::data() as $cat) {
            foreach ($cat['issues'] as $issue) {
                $score = 0;
                foreach (explode(',', $issue['keywords']) as $kw) {
                    $kw = trim($kw);
                    if ($kw !== '' && mb_strpos($text, $kw) !== false) {
                        $score += mb_strlen($kw) >= 3 ? 2 : 1;
                    }
                }
                if ($score > $bestScore) {
                    $bestScore = $score;
                    $best = $issue + ['category' => $cat['name'], 'category_id' => $cat['id']];
                }
            }
        }
        return $bestScore >= 2 ? $best : null;
    }

    /** 把问题整理成一段可以直接展示的推荐答案 */
    public static function render(array $issue): string
    {
        $lines = [];
        $lines[] = '【' . $issue['category'] . '】' . $issue['title'];
        $lines[] = '';
        $lines[] = '可能的原因：' . $issue['symptom'];
        $lines[] = '';
        $lines[] = '推荐处理步骤：';
        foreach ($issue['steps'] as $i => $step) {
            $lines[] = ($i + 1) . '. ' . $step;
        }
        if (!empty($issue['tip'])) {
            $lines[] = '';
            $lines[] = '小贴士：' . $issue['tip'];
        }
        if (!empty($issue['channel'])) {
            $lines[] = '办理入口：' . $issue['channel'];
        }
        return implode("\n", $lines);
    }

